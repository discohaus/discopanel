// Damage lists come from the shared delta source
func init() {
	for proto, regs := range syncedByProtocol {
		for i := range regs {
			if regs[i].Name == "minecraft:damage_type" {
				regs[i].Entries = modernDamageTypes(proto)
			}
		}
	}
}

// Synced set for one protocol when captured
func syncedRegistrySet(protocol int32) ([]syncedRegistry, bool) {
	regs, ok := syncedByProtocol[protocol]
	return regs, ok
}

// Wire id of one entry inside one synced registry
func syncedEntryID(protocol int32, registry, entry string) (int32, bool) {
	for _, reg := range syncedByProtocol[protocol] {
		if reg.Name != registry {
			continue
		}
		for i, name := range reg.Entries {
			if name == entry {
				return int32(i), true
			}
		}
	}
	return 0, false
}

// Baked biome cell id for one protocol
func plainsBiomeID(protocol int32) int32 {
	if id, ok := syncedEntryID(protocol, "minecraft:worldgen/biome", "plains"); ok {
		return id
	}
	return 0
}
